                  } else if (subject == 'الفيزياء') {
                    page = const PhysicsPage();
                  } else if (subject == 'الاجتماعيات') {
                    page = const SocialStudiesPage();
                  } else {
                    page = SubjectPage(subject: subject);
                  }
                  Navigator.push(
                    context,
                    MaterialPageRoute(builder: (_) => page),
                  );
                },
              ),
            ),
          ),
          const SizedBox(height: 16),
          const Center(
            child: Text('ملخصاتي | الثالث المتوسط',
                style: TextStyle(color: Colors.white38)),
          ),
        ],
      ),
    );
  }
}

